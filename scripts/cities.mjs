#!/usr/bin/env node
// Regenerate lib/cities.js: world cities for naming the detected location offline.
//   node scripts/cities.mjs [minPopulation]     (default 15000)
// Source: GeoNames cities15000 (CC BY 4.0, https://www.geonames.org/). Dev-time only; the
// extension never fetches this. Needs `curl` and `unzip`.

import { execFileSync } from 'node:child_process';
import { mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const minPop = Number(process.argv[2] || 15000);
// Skip neighbourhoods and historical/abandoned places: the label should be the town or city.
const SKIP = new Set(['PPLX', 'PPLH', 'PPLQ', 'PPLW', 'PPLCH']);
const dir = mkdtempSync(join(tmpdir(), 'geonames-'));
try {
  const zip = join(dir, 'cities15000.zip');
  execFileSync('curl', ['-sSfL', '-o', zip, 'https://download.geonames.org/export/dump/cities15000.zip']);
  const tsv = execFileSync('unzip', ['-p', zip, 'cities15000.txt'], { maxBuffer: 1 << 28 }).toString('utf8');
  const rows = [];
  for (const line of tsv.split('\n')) {
    const f = line.split('\t');
    if (f.length < 15) continue;
    const name = f[1].replace(/[\t\n\r]/g, ' ').trim();
    const lat = Number(f[4]), lon = Number(f[5]), pop = Number(f[14]), cc = f[8];
    if (!name || !Number.isFinite(lat) || !Number.isFinite(lon) || !(pop >= minPop) || !/^[A-Z]{2}$/.test(cc) || SKIP.has(f[7])) continue;
    rows.push(`${name}\t${cc}\t${lat.toFixed(2)}\t${lon.toFixed(2)}\t${Math.round(pop / 1000)}`);
  }
  if (rows.length < 1000) throw new Error(`only ${rows.length} cities`);
  writeFileSync(new URL('../lib/cities.js', import.meta.url), `// Generated by scripts/cities.mjs — do not edit by hand.
// World cities with population ≥ ${minPop} (no neighbourhoods): "name<TAB>country<TAB>lat<TAB>lon<TAB>thousands"
// per line (${rows.length} cities).
// Data: GeoNames (https://www.geonames.org/), licensed CC BY 4.0.

export const CITIES = ${JSON.stringify(rows.join('\n'))};
`);
  console.log(`lib/cities.js: ${rows.length} cities with population ≥ ${minPop}`);
} finally {
  rmSync(dir, { recursive: true, force: true });
}
