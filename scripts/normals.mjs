#!/usr/bin/env node
// Regenerate lib/normals.js: Philadelphia airport (KPHL) daily normal high/low in °C.
//   node scripts/normals.mjs [firstYear] [lastYear]     (default 2006 2025)
// Uses the Iowa Environmental Mesonet's ASOS daily summaries (dev-time only; the extension
// never fetches this). Each calendar day's normal is the mean over ±15 days, so the curve is smooth.

import { writeFileSync } from 'node:fs';

const [first = 2006, last = 2025] = process.argv.slice(2).map(Number);
const url = 'https://mesonet.agron.iastate.edu/cgi-bin/request/daily.py?' + new URLSearchParams({
  network: 'PA_ASOS', stations: 'PHL', year1: first, month1: 1, day1: 1, year2: last, month2: 12, day2: 31,
  var: 'max_temp_f', format: 'csv', na: 'blank',
}) + '&var=min_temp_f';

const CUM = [0, 31, 59, 90, 120, 151, 181, 212, 243, 273, 304, 334];
const dayIndex = (m, d) => CUM[m - 1] + Math.min(d, m === 2 ? 28 : 31) - 1; // 29 Feb counts as 28 Feb
const f2c = (f) => ((f - 32) * 5) / 9;

const csv = await (await fetch(url)).text();
const hi = Array.from({ length: 365 }, () => []), lo = Array.from({ length: 365 }, () => []);
let rows = 0;
for (const line of csv.trim().split('\n').slice(1)) {
  const [, day, max, min] = line.split(',');
  if (!max || !min) continue;
  const i = dayIndex(Number(day.slice(5, 7)), Number(day.slice(8, 10)));
  hi[i].push(f2c(Number(max)));
  lo[i].push(f2c(Number(min)));
  rows++;
}
if (rows < 300 * (last - first + 1)) throw new Error(`only ${rows} days of data`);

const smooth = (src) => Array.from({ length: 365 }, (_, i) => {
  const v = [];
  for (let k = -15; k <= 15; k++) v.push(...src[(i + k + 365) % 365]);
  return Math.round((v.reduce((a, b) => a + b, 0) / v.length) * 10) / 10;
});

const out = `// Generated by scripts/normals.mjs — do not edit by hand.
// Philadelphia airport (KPHL) daily normal high/low, °C, ${first}–${last}, each day averaged over ±15 days.
// Source: Iowa Environmental Mesonet ASOS daily summaries (${rows} days).

const HI = [${smooth(hi).join(',')}];
const LO = [${smooth(lo).join(',')}];
const CUM = [0, 31, 59, 90, 120, 151, 181, 212, 243, 273, 304, 334];

/** Normal high/low (°C) for 'YYYY-MM-DD'; 29 Feb uses 28 Feb. Null for a malformed date. */
export function normalFor(date) {
  const m = Number(String(date).slice(5, 7)), d = Number(String(date).slice(8, 10));
  if (!(m >= 1 && m <= 12 && d >= 1 && d <= 31)) return null;
  const i = CUM[m - 1] + Math.min(d, m === 2 ? 28 : 31) - 1;
  return { hi: HI[i], lo: LO[i] };
}
`;
writeFileSync(new URL('../lib/normals.js', import.meta.url), out);
console.log(`lib/normals.js: ${first}–${last}, ${rows} days`);
