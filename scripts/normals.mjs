#!/usr/bin/env node
// Regenerate lib/normals.js: Philadelphia airport (KPHL) daily normal high/low in °C.
//   node scripts/normals.mjs [firstYear] [lastYear]     (default 2006 2025)
// Uses the Iowa Environmental Mesonet's ASOS daily summaries (dev-time only; the extension
// never fetches this). Each calendar day's normal is the mean over ±15 days, so the curve is smooth.

import { writeFileSync } from 'node:fs';
import { normalsFromDaily } from '../lib/climate.js';

const [first = 2006, last = 2025] = process.argv.slice(2).map(Number);
const url = 'https://mesonet.agron.iastate.edu/cgi-bin/request/daily.py?' + new URLSearchParams({
  network: 'PA_ASOS', stations: 'PHL', year1: first, month1: 1, day1: 1, year2: last, month2: 12, day2: 31,
  var: 'max_temp_f', format: 'csv', na: 'blank',
}) + '&var=min_temp_f';

const f2c = (f) => ((f - 32) * 5) / 9;
const csv = await (await fetch(url)).text();
const times = [], highs = [], lows = [];
for (const line of csv.trim().split('\n').slice(1)) {
  const [, day, max, min] = line.split(',');
  if (!max || !min) continue;
  times.push(day);
  highs.push(f2c(Number(max)));
  lows.push(f2c(Number(min)));
}
if (times.length < 300 * (last - first + 1)) throw new Error(`only ${times.length} days of data`);
const { hi, lo } = normalsFromDaily(times, highs, lows);

writeFileSync(new URL('../lib/normals.js', import.meta.url), `// Generated by scripts/normals.mjs — do not edit by hand.
// Philadelphia airport (KPHL) daily normal high/low, °C, ${first}–${last}, each day averaged over ±15 days.
// Source: Iowa Environmental Mesonet ASOS daily summaries (${times.length} days).

export const KPHL = {
  hi: [${hi.join(',')}],
  lo: [${lo.join(',')}],
};
`);
console.log(`lib/normals.js: ${first}–${last}, ${times.length} days`);
